SET NOCOUNT ON;
DECLARE @AsOfDate date = COALESCE(@TestDate, CONVERT(date, GETDATE()));
DECLARE @Tomorrow date = DATEADD(day, 1, @AsOfDate);

-- 135で抽出した3本の共通条件。TRUNCの比較を日単位の範囲条件へ変換する。
-- 最大の開始日ではなく、当日に有効な行の最大IDを選択する。
SELECT MAR.MEISHO4_NK AS ShopName, UKA.UK_KEIYAKU_ID,
       UKB.SUPPORT_ID, UKB.HOSYU_GKIN
INTO #McmMaintenanceActive
FROM MCM.MCM_UK_KEIYAKU UKA
JOIN MCM.MCM_UK_KIKAN UKB ON UKB.UK_KEIYAKU_ID = UKA.UK_KEIYAKU_ID
JOIN MCM.MCM_UK_SEIBAN UKI ON UKI.UK_KEIYAKU_ID = UKA.UK_KEIYAKU_ID
JOIN MCM.MCM_MA_TENPO MAR ON MAR.TENPO_ID = UKB.IRAITENPO_ID
WHERE UKA.JOTAI = N'2'
  AND (UKA.KAIYAKU_DT IS NULL OR UKA.KAIYAKU_DT >= @AsOfDate)
  AND ((UKA.ENTYOKEIYAKUMANRYO_DT IS NULL
        AND (UKA.KEIYAKUMANRYO_DT IS NULL OR UKA.KEIYAKUMANRYO_DT >= @AsOfDate))
       OR UKA.ENTYOKEIYAKUMANRYO_DT >= @AsOfDate)
  AND UKI.UK_SEIBAN_ID = (
      SELECT MAX(UKZ.UK_SEIBAN_ID)
      FROM MCM.MCM_UK_SEIBAN UKZ
      WHERE UKZ.UK_KEIYAKU_ID = UKA.UK_KEIYAKU_ID
        AND UKZ.KAISI_DT < @Tomorrow AND UKZ.SYURYO_DT >= @AsOfDate)
  AND UKB.UK_KIKAN_ID = (
      SELECT MAX(SS.UK_KIKAN_ID)
      FROM MCM.MCM_UK_KIKAN SS
      WHERE SS.UK_KEIYAKU_ID = UKA.UK_KEIYAKU_ID AND SS.YUKO_FLG = 0
        AND SS.KAISI_DT < @Tomorrow AND SS.SYURYO_DT >= @AsOfDate);

SELECT @AsOfDate AS AsOfDate;
SELECT ShopName, SUM(HOSYU_GKIN) AS Amount
FROM #McmMaintenanceActive GROUP BY ShopName ORDER BY ShopName;
SELECT ShopName, COUNT_BIG(*) AS ContractCount
FROM (SELECT ShopName, UK_KEIYAKU_ID FROM #McmMaintenanceActive
      GROUP BY ShopName, UK_KEIYAKU_ID) D
GROUP BY ShopName ORDER BY ShopName;
-- NULLのサポートIDもGROUP BY後の1行として数える。COUNT(DISTINCT)に置換しない。
SELECT ShopName, COUNT_BIG(*) AS SupportCount
FROM (SELECT ShopName, SUPPORT_ID FROM #McmMaintenanceActive
      GROUP BY ShopName, SUPPORT_ID) D
GROUP BY ShopName ORDER BY ShopName;
DROP TABLE #McmMaintenanceActive;
