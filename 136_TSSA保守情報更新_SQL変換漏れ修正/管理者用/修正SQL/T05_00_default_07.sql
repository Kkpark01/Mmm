SELECT
  CONCAT(
    CAST(N'' AS NVARCHAR(MAX)),
    CASE
      WHEN (
        CASE
          WHEN DATALENGTH(CAST(CAST(TKE.KOTAIKANRI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))) = 0
          THEN NULL
          ELSE CAST(CAST(TKE.KOTAIKANRI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))
        END
      ) IS NULL
      THEN NULL
      WHEN (
        LEN(
          CONCAT(
            (
              CASE
                WHEN DATALENGTH(CAST(CAST(TKE.KOTAIKANRI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))) = 0
                THEN NULL
                ELSE CAST(CAST(TKE.KOTAIKANRI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))
              END
            ),
            N'#'
          )
        ) - 1
      ) >= 8
      THEN LEFT(
        (
          CASE
            WHEN DATALENGTH(CAST(CAST(TKE.KOTAIKANRI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))) = 0
            THEN NULL
            ELSE CAST(CAST(TKE.KOTAIKANRI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))
          END
        ),
        8
      )
      ELSE CONCAT(
        LEFT(
          REPLICATE(N'0', 8),
          8 - (
            LEN(
              CONCAT(
                (
                  CASE
                    WHEN DATALENGTH(CAST(CAST(TKE.KOTAIKANRI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))) = 0
                    THEN NULL
                    ELSE CAST(CAST(TKE.KOTAIKANRI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))
                  END
                ),
                N'#'
              )
            ) - 1
          )
        ),
        (
          CASE
            WHEN DATALENGTH(CAST(CAST(TKE.KOTAIKANRI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))) = 0
            THEN NULL
            ELSE CAST(CAST(TKE.KOTAIKANRI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))
          END
        )
      )
    END,
    N' / ',
    CASE
      WHEN (
        CASE
          WHEN DATALENGTH(CAST(CAST(TKD.KIKIMEISAI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))) = 0
          THEN NULL
          ELSE CAST(CAST(TKD.KIKIMEISAI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))
        END
      ) IS NULL
      THEN NULL
      WHEN (
        LEN(
          CONCAT(
            (
              CASE
                WHEN DATALENGTH(CAST(CAST(TKD.KIKIMEISAI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))) = 0
                THEN NULL
                ELSE CAST(CAST(TKD.KIKIMEISAI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))
              END
            ),
            N'#'
          )
        ) - 1
      ) >= 8
      THEN LEFT(
        (
          CASE
            WHEN DATALENGTH(CAST(CAST(TKD.KIKIMEISAI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))) = 0
            THEN NULL
            ELSE CAST(CAST(TKD.KIKIMEISAI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))
          END
        ),
        8
      )
      ELSE CONCAT(
        LEFT(
          REPLICATE(N'0', 8),
          8 - (
            LEN(
              CONCAT(
                (
                  CASE
                    WHEN DATALENGTH(CAST(CAST(TKD.KIKIMEISAI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))) = 0
                    THEN NULL
                    ELSE CAST(CAST(TKD.KIKIMEISAI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))
                  END
                ),
                N'#'
              )
            ) - 1
          )
        ),
        (
          CASE
            WHEN DATALENGTH(CAST(CAST(TKD.KIKIMEISAI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))) = 0
            THEN NULL
            ELSE CAST(CAST(TKD.KIKIMEISAI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))
          END
        )
      )
    END
  ) AS C001,
  TKA.TK_KEIYAKU_ID AS C002,
  TKE.KOTAIKANRI_ID AS C003,
  TKD.KIKIMEISAI_ID AS C004,
  CONCAT(CAST(N'' AS NVARCHAR(MAX)), MAE.HYOJIJUN, N'-', MAG.HYOJIJUN, N'-', MAF.HYOJIJUN) AS C005,
  TKB.PLANT_ID AS C006,
  TKB.SUPPORT_ID AS C007,
  MAA.NONYUSAKI_NK AS C008,
  MAA.NONYUSAKIKOJO_NK AS C009,
  MAB.PLANT_NK AS C010,
  MAD.BRANDSYOSAI_NK AS C011,
  MAE.KIKIKOSEI_NK AS C012,
  MAG.SETCHIBASYO AS C013,
  MAG.KOTAI_NK AS C014,
  CASE
    WHEN (
      CASE
        WHEN DATALENGTH(CAST(CAST(TKD.ATSUKAIKIKI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))) = 0
        THEN NULL
        ELSE CAST(CAST(TKD.ATSUKAIKIKI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))
      END
    ) IS NULL
    THEN NULL
    WHEN (
      LEN(
        CONCAT(
          (
            CASE
              WHEN DATALENGTH(CAST(CAST(TKD.ATSUKAIKIKI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))) = 0
              THEN NULL
              ELSE CAST(CAST(TKD.ATSUKAIKIKI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))
            END
          ),
          N'#'
        )
      ) - 1
    ) >= 8
    THEN LEFT(
      (
        CASE
          WHEN DATALENGTH(CAST(CAST(TKD.ATSUKAIKIKI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))) = 0
          THEN NULL
          ELSE CAST(CAST(TKD.ATSUKAIKIKI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))
        END
      ),
      8
    )
    ELSE CONCAT(
      LEFT(
        REPLICATE(N'0', 8),
        8 - (
          LEN(
            CONCAT(
              (
                CASE
                  WHEN DATALENGTH(CAST(CAST(TKD.ATSUKAIKIKI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))) = 0
                  THEN NULL
                  ELSE CAST(CAST(TKD.ATSUKAIKIKI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))
                END
              ),
              N'#'
            )
          ) - 1
        )
      ),
      (
        CASE
          WHEN DATALENGTH(CAST(CAST(TKD.ATSUKAIKIKI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))) = 0
          THEN NULL
          ELSE CAST(CAST(TKD.ATSUKAIKIKI_ID AS NVARCHAR(MAX)) AS NVARCHAR(MAX))
        END
      )
    )
  END AS C015,
  TKD.SEIZOMAKER_NK AS C016,
  MAH.ATSUKAIKIKI_NK AS C017,
  MAH.KATASHIKI AS C018,
  MAF.SURYO_NM AS C019,
  MAG.SERIAL_NO AS C020,
  CONVERT(NVARCHAR(10), MAG.KEIYAKUKIGEN_DT, 23) AS C021,
  CONVERT(NVARCHAR(10), MAG.ENCHOKEIYAKUKIGEN_DT, 23) AS C022,
  MAE.BIKO AS C023,
  MAF.BIKO AS C024,
  MAG.BIKO AS C025,
  MAK.TORIHIKISAKI_NK AS C026,
  CONVERT(NVARCHAR(10), TKA.SHOKAI_KEIYAKU_DT, 23) AS C027,
  CONVERT(NVARCHAR(10), TKB.KAISI_DT, 23) AS C028,
  CONVERT(NVARCHAR(10), TKB.SYURYO_DT, 23) AS C029,
  CASE
    WHEN MAG.KEIYAKUKIGEN_DT IS NULL
    THEN CONVERT(
      NVARCHAR(10),
      CASE
        WHEN CONVERT(DATE, DATEADD(DAY, -1, TKA.SHOKAI_KEIYAKU_DT)) = EOMONTH(CAST(DATEADD(DAY, -1, TKA.SHOKAI_KEIYAKU_DT) AS DATE))
        THEN DATEADD(
          DAY,
          DATEDIFF(
            DAY,
            CAST(CONVERT(DATE, DATEADD(MONTH, 144, DATEADD(DAY, -1, TKA.SHOKAI_KEIYAKU_DT))) AS DATETIME2),
            CAST(EOMONTH(CAST(DATEADD(MONTH, 144, DATEADD(DAY, -1, TKA.SHOKAI_KEIYAKU_DT)) AS DATE)) AS DATETIME2)
          ),
          DATEADD(MONTH, 144, DATEADD(DAY, -1, TKA.SHOKAI_KEIYAKU_DT))
        )
        ELSE DATEADD(MONTH, 144, DATEADD(DAY, -1, TKA.SHOKAI_KEIYAKU_DT))
      END,
      111
    )
    WHEN MAG.ENCHOKEIYAKUKIGEN_DT IS NULL
    THEN CONVERT(NVARCHAR(10), MAG.KEIYAKUKIGEN_DT, 23)
    ELSE CONVERT(NVARCHAR(10), MAG.ENCHOKEIYAKUKIGEN_DT, 23)
  END AS C030,
  CONVERT(NVARCHAR(10), TKA.KEIYAKUMANRYO_DT, 23) AS C031,
  CONVERT(NVARCHAR(10), TKA.KAIYAKU_DT, 23) AS C032,
  TKA.KEIYAKU_NO AS C033,
  TKA.PACK_FLG AS C034,
  TKJ.KAISU AS C035,
  CASE
    WHEN TKJ.KAISU = 1 OR TKJ.KAISU = 12
    THEN TKJ.KAISU
    WHEN TKJ.KAISU = 0 OR TKJ.KAISU IS NULL
    THEN 1
    WHEN TKB.TORIHIKISAKI_ID = 38
    THEN 4
    ELSE 12
  END AS C036,
  MAQ.HOSYUJIKAN_DT AS C037,
  CASE
    WHEN MAQ.HOSYUJIKAN_DT <> 8 AND MAQ.HOSYUJIKAN_DT <> 24
    THEN 8
    WHEN MAQ.HOSYUJIKAN_DT IS NULL
    THEN 8
    ELSE MAQ.HOSYUJIKAN_DT
  END AS C038,
  CASE
    WHEN MAQ.HOSYUJIKAN_DT IS NULL
    THEN N'9:00'
    WHEN MAQ.HOSYUJIKAN_DT = 24
    THEN N'0:00'
    ELSE CONCAT(
      CAST(N'' AS NVARCHAR(MAX)),
      SUBSTRING(
        CAST(MAQ.KAISIJIKAN_DT AS NVARCHAR(MAX)),
        1,
        LEN(CAST(MAQ.KAISIJIKAN_DT AS NVARCHAR(MAX))) - 2
      ),
      N':',
      RIGHT(CAST(MAQ.KAISIJIKAN_DT AS NVARCHAR(MAX)), 2)
    )
  END AS C039,
  CASE
    WHEN MAQ.HOSYUJIKAN_DT IS NULL
    THEN N'17:00'
    WHEN MAQ.HOSYUJIKAN_DT = 24
    THEN N'24:00'
    ELSE CONCAT(
      CAST(N'' AS NVARCHAR(MAX)),
      SUBSTRING(CAST(MAQ.SYURYOJIKAN_DT AS NVARCHAR(MAX)), 1, 2),
      N':',
      RIGHT(CAST(MAQ.SYURYOJIKAN_DT AS NVARCHAR(MAX)), 2)
    )
  END AS C040,
  TKH.TENKENKAISU AS C041,
  CASE
    WHEN TKF.HOSYUHOHO = N'F'
    THEN N'オンサイト'
    WHEN TKF.HOSYUHOHO = N'S' OR TKF.HOSYUHOHO = N'C' OR TKF.HOSYUHOHO IS NULL
    THEN N'センドバック'
    WHEN TKF.HOSYUHOHO = N'T'
    THEN N'電話応答'
    ELSE TKF.HOSYUHOHO
  END AS C042,
  CONCAT(
    CAST(N'' AS NVARCHAR(MAX)),
    CASE
      WHEN MAQ.KAISIYOBI = N'1'
      THEN N'日'
      WHEN MAQ.KAISIYOBI = N'2' OR MAQ.KAISIYOBI IS NULL
      THEN N'月'
      WHEN MAQ.KAISIYOBI = N'6'
      THEN N'金'
      WHEN MAQ.KAISIYOBI = N'7'
      THEN N'土'
      ELSE N''
    END,
    N'－',
    CASE
      WHEN MAQ.SYURYOYOBI = N'1'
      THEN N'日'
      WHEN MAQ.SYURYOYOBI = N'2'
      THEN N'月'
      WHEN MAQ.SYURYOYOBI = N'6' OR MAQ.SYURYOYOBI IS NULL
      THEN N'金'
      WHEN MAQ.SYURYOYOBI = N'7'
      THEN N'土'
      ELSE N''
    END
  ) AS C043,
  CASE
    WHEN TKH.TENKENKANOYOBI = N'1'
    THEN N'月－金'
    WHEN TKH.TENKENKANOYOBI = N'2'
    THEN N'月－土'
    WHEN TKH.TENKENKANOYOBI = N'3'
    THEN N'月－日'
    ELSE N''
  END AS C044,
  TKH.YAKANTAIOUMU AS C045,
  TKH.BIKO AS C046,
  TKF.SIKIRI_KIN AS C047,
  CASE
    WHEN MCM_MONTHS.CONTRACT_MONTHS = 12
    OR TKJ.KAISU = 1 /* 契約月数が12ヶ月 or 支払回数が1回 */
    THEN TKF.SIKIRI_KIN
    ELSE (
      CAST(TKF.SIKIRI_KIN AS FLOAT) / MCM_MONTHS.CONTRACT_MONTHS
    ) * 12 /* 仕切単価 / 契約月数 * 12 */
  END AS C048,
  TKB.SYUSSEINEBIKI_KIN AS C049,
  TKA.PACKKEIYAKUNAIYO AS C050,
  REPLACE(TKA.BIKO, CONCAT(CAST(N'' AS NVARCHAR(MAX)), NCHAR(13), NCHAR(10)), N' ') AS C051
FROM MCM.MCM_TK_KIKAN AS TKB
JOIN MCM.MCM_TK_KEIYAKU AS TKA
  ON TKA.TK_KEIYAKU_ID = TKB.TK_KEIYAKU_ID
JOIN MCM.MCM_TK_KIKIKOSEI AS TKC
  ON TKB.TK_KIKAN_ID = TKC.TK_KIKAN_ID
JOIN MCM.MCM_TK_KIKIMEISAI AS TKD
  ON TKC.TK_KIKIKOSEI_ID = TKD.TK_KIKIKOSEI_ID
JOIN MCM.MCM_TK_KOTAIMEISAI AS TKE
  ON TKD.TK_KIKIMEISAI_ID = TKE.TK_KIKIMEISAI_ID
JOIN MCM.MCM_TK_TANKA AS TKF
  ON TKD.TK_KIKIMEISAI_ID = TKF.TK_KIKIMEISAI_ID
JOIN MCM.MCM_TK_TENKEN AS TKH
  ON TKC.TK_KIKIKOSEI_ID = TKH.TK_KIKIKOSEI_ID
  AND TKD.TK_KIKIKOSEI_ID = TKH.TK_KIKIKOSEI_ID
JOIN MCM.MCM_TK_SIHARAI AS TKJ
  ON TKB.TK_KIKAN_ID = TKJ.TK_KIKAN_ID AND TKC.TK_KIKAN_ID = TKJ.TK_KIKAN_ID
/* - 納入先マスタ */
JOIN MCM.MCM_MA_NONYUSAKI AS MAA
  ON TKB.NONYUSAKI_ID = MAA.NONYUSAKI_ID
/* - プラントマスタ */
JOIN MCM.MCM_MA_PLANT AS MAB
  ON TKB.PLANT_ID = MAB.PLANT_ID
/* - 機器構成 */
JOIN MCM.MCM_MA_KIKIKOSEI AS MAE
  ON TKC.KIKIKOSEI_ID = MAE.KIKIKOSEI_ID
/* - 機器明細 */
JOIN MCM.MCM_MA_KIKIMEISAI AS MAF
  ON TKD.KIKIMEISAI_ID = MAF.KIKIMEISAI_ID
/* - 機器個体管理 */
JOIN MCM.MCM_MA_KIKIKOTAIKANRI AS MAG
  ON TKE.KOTAIKANRI_ID = MAG.KOTAIKANRI_ID
/* - ブランド */
JOIN MCM.MCM_MA_BRAND_KOSEI AS MAD
  ON MAG.BRANDKOSEI_ID = MAD.BRANDKOSEI_ID
/* - 取扱機器マスタ */
JOIN MCM.MCM_MA_ATSUKAIKIKI AS MAH
  ON TKD.ATSUKAIKIKI_ID = MAH.ATSUKAIKIKI_ID
/* - 取引先マスタ */
JOIN MCM.MCM_MA_TORIHIKISAKI AS MAK
  ON TKB.TORIHIKISAKI_ID = MAK.TORIHIKISAKI_ID
/* - 機器分類 */
JOIN MCM.MCM_MA_KIKIBUNRUI AS MAM
  ON MAH.KIKIBUNRUI_ID = MAM.KIKIBUNRUI_ID
/* - 取引先保守時間 */
LEFT OUTER JOIN MCM.MCM_MA_TORIHOSYUJIKAN AS MAQ
  ON TKF.TORIHOSYUJIKAN_ID = MAQ.TORIHOSYUJIKAN_ID
/* Oracle MONTHS_BETWEEN: same day/month-end uses whole months; otherwise 31-day fractions. */
CROSS APPLY (VALUES (DATEADD(DAY, 1, TKB.SYURYO_DT))) AS MCM_DATE(END_NEXT)
CROSS APPLY (VALUES (
    CAST(DATEDIFF(MONTH, TKB.KAISI_DT, MCM_DATE.END_NEXT) AS FLOAT)
    + CASE
        WHEN DAY(TKB.KAISI_DT) = DAY(MCM_DATE.END_NEXT)
          OR (CONVERT(DATE, TKB.KAISI_DT) = EOMONTH(TKB.KAISI_DT)
              AND CONVERT(DATE, MCM_DATE.END_NEXT) = EOMONTH(MCM_DATE.END_NEXT))
        THEN 0.0
        ELSE (DAY(MCM_DATE.END_NEXT) - DAY(TKB.KAISI_DT)
              + (DATEDIFF(SECOND, CONVERT(DATE, MCM_DATE.END_NEXT), MCM_DATE.END_NEXT)
                 - DATEDIFF(SECOND, CONVERT(DATE, TKB.KAISI_DT), TKB.KAISI_DT)) / 86400E0) / 31E0
      END
)) AS MCM_MONTHS(CONTRACT_MONTHS)
WHERE
  TKA.JOTAI = 2
  AND (
    TKA.SHONINJOTAI = N'3'
    OR TKA.SHONINJOTAI = N'2'
    OR TKA.SHONINJOTAI = N'1'
    OR TKA.SHONINJOTAI = N'0'
  )
  AND TKB.TK_KIKAN_ID = (
    SELECT
      MAX(ZZZ.TK_KIKAN_ID)
    FROM MCM.MCM_TK_KIKAN AS ZZZ
    WHERE
      ZZZ.TK_KEIYAKU_ID = TKA.TK_KEIYAKU_ID
      AND ZZZ.KAISI_DT <= CONVERT(DATE, EOMONTH(CAST(GETDATE() AS DATE)))
      AND ZZZ.SYURYO_DT >= CONVERT(DATE, EOMONTH(CAST(GETDATE() AS DATE)))
  )
  AND TKH.OYAKIKIBUNRUI_CD = MAM.OYAKIKIBUNRUI_CD
ORDER BY
  CASE WHEN TKB.SUPPORT_ID IS NULL THEN 1 ELSE 0 END, TKB.SUPPORT_ID ASC,
  CASE WHEN TKB.PLANT_ID IS NULL THEN 1 ELSE 0 END, TKB.PLANT_ID ASC,
  CASE WHEN MAD.HYOJIJUN IS NULL THEN 1 ELSE 0 END, MAD.HYOJIJUN ASC,
  CASE WHEN MAE.HYOJIJUN IS NULL THEN 1 ELSE 0 END, MAE.HYOJIJUN ASC,
  CASE WHEN MAG.HYOJIJUN IS NULL THEN 1 ELSE 0 END, MAG.HYOJIJUN ASC,
  CASE WHEN MAF.HYOJIJUN IS NULL THEN 1 ELSE 0 END, MAF.HYOJIJUN ASC;
