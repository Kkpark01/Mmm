-- チケット618：読み取り専用の調査用SQL。アプリへの配置・DB定義変更は不要。
-- 対象DBへ接続し、以下2値を実際の値に設定してから実行する。
-- INT06-03はテスト項番である可能性があるため、実契約番号として決め打ちしない。
-- 当方では本SQL・帳票テストとも未実行。
DECLARE @TargetContractNo NVARCHAR(100) = NULL; -- 実際の契約NO
DECLARE @SwitchMonth DATE = NULL;             -- 新期間の開始月の月初（例：2026-10-01）

IF @TargetContractNo IS NULL OR @SwitchMonth IS NULL OR DAY(@SwitchMonth) <> 1
    THROW 50000, N'実際の契約NOと、切替月の月初日を設定してください。', 1;

-- 1. 接続先・配備済みビュー定義。
SELECT CAST(SERVERPROPERTY('ServerName') AS NVARCHAR(128)) AS SERVER_NAME,
       DB_NAME() AS DATABASE_NAME;
SELECT OBJECT_SCHEMA_NAME(O.object_id) AS SCHEMA_NAME, O.name AS OBJECT_NAME, M.definition
  FROM sys.objects O LEFT JOIN sys.sql_modules M ON M.object_id = O.object_id
 WHERE O.object_id IN (OBJECT_ID(N'MCM.MCM_TK_SIHARAI_V'), OBJECT_ID(N'MCM.MCM_TU_KEIYAKU_V'));

-- 2. 同じ契約の全期間。旧・新の開始日、YUKO_FLG、契約状態、金額を確認。
SELECT A.TK_KEIYAKU_ID, A.KEIYAKU_NO, A.JOTAI, A.KAIYAKU_DT,
       B.TK_KIKAN_ID, B.KAISI_DT, B.SYURYO_DT, B.YUKO_FLG, B.SIKIRIGOKEI_KIN,
       J.TK_SIHARAI_ID, J.KAISU, K.TK_SIHARAIMEISAI_ID, K.TSUKI, K.ON_FLG, K.OFF_FLG
  FROM MCM.MCM_TK_KEIYAKU A JOIN MCM.MCM_TK_KIKAN B ON B.TK_KEIYAKU_ID = A.TK_KEIYAKU_ID
  LEFT JOIN MCM.MCM_TK_SIHARAI J ON J.TK_KIKAN_ID = B.TK_KIKAN_ID
  LEFT JOIN MCM.MCM_TK_SIHARAIMEISAI K ON K.TK_SIHARAI_ID = J.TK_SIHARAI_ID
       AND K.TSUKI >= DATEADD(MONTH, -1, @SwitchMonth)
       AND K.TSUKI < DATEADD(MONTH, 1, @SwitchMonth)
 WHERE A.KEIYAKU_NO = @TargetContractNo
 ORDER BY A.TK_KEIYAKU_ID, B.KAISI_DT, B.TK_KIKAN_ID, K.TSUKI;

-- 3. VBの月単位の規則により採用すべき期間。最大ID・現在日付では選ばない。
WITH TARGET_MONTHS AS (
    SELECT DATEADD(MONTH, -1, @SwitchMonth) AS TSUKI
    UNION ALL SELECT @SwitchMonth
)
SELECT A.TK_KEIYAKU_ID, A.KEIYAKU_NO, M.TSUKI,
       B.TK_KIKAN_ID AS EXPECTED_TK_KIKAN_ID, B.KAISI_DT, B.SYURYO_DT, B.YUKO_FLG
  FROM MCM.MCM_TK_KEIYAKU A CROSS JOIN TARGET_MONTHS M
  LEFT JOIN MCM.MCM_TK_KIKAN B ON B.TK_KEIYAKU_ID = A.TK_KEIYAKU_ID
       AND B.YUKO_FLG <= 0 AND B.KAISI_DT = (
           SELECT MAX(SB.KAISI_DT) FROM MCM.MCM_TK_KIKAN SB
            WHERE SB.TK_KEIYAKU_ID = A.TK_KEIYAKU_ID AND SB.YUKO_FLG <= 0
              AND DATEFROMPARTS(YEAR(SB.KAISI_DT), MONTH(SB.KAISI_DT), 1) <= M.TSUKI)
 WHERE A.KEIYAKU_NO = @TargetContractNo
 ORDER BY A.TK_KEIYAKU_ID, M.TSUKI, B.TK_KIKAN_ID;

-- 4. 配備済み支払ビューが実際に返す期間。3の期待期間と照合。
SELECT V.TK_KEIYAKU_ID, V.TK_KIKAN_ID, V.TK_SIHARAI_ID, V.TK_SIHARAIMEISAI_ID,
       V.UK_KEIYAKU_ID, V.KEIYAKU_NO, V.TSUKI, V.KAISI_DT, V.SYURYO_DT,
       V.SIHARAI, V.KAISU, V.HARD_SEIBAN
  FROM MCM.MCM_TK_SIHARAI_V V
 WHERE V.KEIYAKU_NO = @TargetContractNo
   AND V.TSUKI >= DATEADD(MONTH, -1, @SwitchMonth)
   AND V.TSUKI < DATEADD(MONTH, 1, @SwitchMonth)
 ORDER BY V.TSUKI, V.TK_KIKAN_ID, V.HARD_SEIBAN;

-- 5. 新旧の契約期間が参照する単価・見積期間。実計算の金額元はTMGの仕切合計。
-- 契約期間の表示金額を直しただけでは、ここが旧見積のままなら旧金額になる。
SELECT DISTINCT A.TK_KEIYAKU_ID, B.TK_KIKAN_ID, B.KAISI_DT AS TK_KAISI_DT,
       B.SYURYO_DT AS TK_SYURYO_DT, B.SIKIRIGOKEI_KIN AS TK_GOKEI_KIN,
       F.TK_TANKA_ID, F.TM_TANKA_ID, F.KAISI_DT AS TK_TANKA_KAISI_DT,
       F.SYURYO_DT AS TK_TANKA_SYURYO_DT, F.SIKIRI_KIN AS TK_SIKIRI_KIN,
       G.TM_KIKAN_ID, G.KAISI_DT AS TM_KAISI_DT, G.SYURYO_DT AS TM_SYURYO_DT,
       G.SIKIRIGOKEI_KIN AS PAYMENT_RATE_AMOUNT
  FROM MCM.MCM_TK_KEIYAKU A JOIN MCM.MCM_TK_KIKAN B ON B.TK_KEIYAKU_ID = A.TK_KEIYAKU_ID
  LEFT JOIN MCM.MCM_TK_KIKIKOSEI C ON C.TK_KIKAN_ID = B.TK_KIKAN_ID
  LEFT JOIN MCM.MCM_TK_KIKIMEISAI D ON D.TK_KIKIKOSEI_ID = C.TK_KIKIKOSEI_ID
  LEFT JOIN MCM.MCM_TK_TANKA F ON F.TK_KIKIMEISAI_ID = D.TK_KIKIMEISAI_ID
  LEFT JOIN MCM.MCM_TM_TANKA MF ON MF.TM_TANKA_ID = F.TM_TANKA_ID
  LEFT JOIN MCM.MCM_TM_KIKAN G ON G.TM_KIKAN_ID = MF.TM_KIKAN_ID
 WHERE A.KEIYAKU_NO = @TargetContractNo
 ORDER BY A.TK_KEIYAKU_ID, B.TK_KIKAN_ID, G.TM_KIKAN_ID, F.TK_TANKA_ID;

-- 6. 取引先契約とユーザ契約の関連・確認済み製番の成立を確認。
SELECT V.TK_KEIYAKU_ID, V.TK_KIKAN_ID, V.KAISI_DT AS TU_KAISI_DT,
       U.UK_KEIYAKU_ID, U.HARD_SEIBAN, U.KAKUNIN_KBN,
       U.KAISI_DT AS SEIBAN_KAISI_DT, U.SYURYO_DT AS SEIBAN_SYURYO_DT
  FROM MCM.MCM_TK_KEIYAKU A JOIN MCM.MCM_TU_KEIYAKU_V V ON V.TK_KEIYAKU_ID = A.TK_KEIYAKU_ID
  LEFT JOIN MCM.MCM_UK_SEIBAN U ON U.UK_KEIYAKU_ID = V.UK_KEIYAKU_ID
 WHERE A.KEIYAKU_NO = @TargetContractNo
 ORDER BY V.TK_KIKAN_ID, U.UK_KEIYAKU_ID, U.HARD_SEIBAN;
